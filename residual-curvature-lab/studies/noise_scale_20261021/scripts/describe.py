"""Descriptive tables D (PROTOCOL.md, section 4) from results/noise/*.json, after summarize.py.

Usage (from residual-curvature-lab/): describe.py
Writes studies/noise_scale_20261021/results/descriptive.json and descriptive.md. Reuses summarize.theory and
summarize.crossings, and checks that the pooled theory values equal results/summary.json exactly.
"""
import json
import statistics
import sys

import summarize
from summarize import ARMS, B, FINE, GRID, RESULTS, SEEDS, STATES

KINDS = {'query+key': ('attention.query', 'attention.key'), 'value+output': ('attention.value', 'attention.output'),
         'w1': ('.w1.',), 'w2': ('.w2.',), 'input': ('input.',), 'head': ('head.',)}


def kind_state(state, patterns):
    return {'tensors': {n: t for n, t in state['tensors'].items() if any(p in n for p in patterns)}}


def span(values, d=3):
    lo, hi = min(values), max(values)
    f = lambda v: f'{v:.{d}g}'
    return f(lo) if f(lo) == f(hi) else f'{f(lo)}–{f(hi)}'


def main():
    summary = json.loads((RESULTS/'summary.json').read_text())
    outs = {(a, s): json.loads((RESULTS/'noise'/f'{a}_s{s}.json').read_text()) for a in ARMS for s in SEEDS}
    rows, kinds = {}, {}
    for (a, s), out in outs.items():
        for t in STATES:
            state = out['states'][str(t)]
            key = f'{a}_s{s}_t{t}'
            th = summarize.theory(state)
            stored = summary['cases'][key]['theory']
            if any(th[nu][q] != stored[str(nu)][q] for nu in FINE for q in th[nu]):
                raise RuntimeError(f'theory mismatch against summary.json: {key}')
            pairs, required = summarize.crossings(th)
            steps = state['score']['steps']
            evaluation = {nu: steps[str(nu)]['evaluation'] for nu in GRID}
            validation = {nu: steps[str(nu)]['validation'] for nu in GRID}
            rows[key] = {
                'arm': a, 'seed': s, 'step': t, 'delta': state['delta'], 'mu': state['mu'],
                'phi_ratio_1_0': th[1.0]['phi']/th[0.0]['phi'],
                'K': {nu: th[nu]['K'] for nu in GRID}, 'N': {nu: th[nu]['N'] for nu in GRID},
                'pairs': pairs, 'B_required': required,
                'argmax_pair': max(pairs, key=lambda p: pairs[p]['B_crit']),
                'pairs_above_B': [p for p, v in pairs.items() if v['B_crit'] >= B],
                'theory_best_fine': max(FINE, key=lambda nu: th[nu]['psi']),
                'psi_ratio_to_0': {nu: th[nu]['psi']/th[0.]['psi'] for nu in GRID},
                'evaluation': evaluation, 'best': max(evaluation, key=evaluation.get),
                'validation': validation, 'validation_best': max(validation, key=validation.get),
                'eval_ratio_to_0': {nu: evaluation[nu]/evaluation[0.] for nu in GRID},
                'multiplier': {nu: steps[str(nu)]['multiplier'] for nu in GRID},
                'edge': [nu for nu in GRID if not steps[str(nu)]['interior']],
                'min_ritz_over_delta': min(x['min_ritz_over_delta'] for x in state['tensors'].values())}
            for name, patterns in KINDS.items():
                kt = summarize.theory(kind_state(state, patterns))
                kinds.setdefault(name, {})[key] = {
                    'K0': kt[0.]['K'], 'K1': kt[1.]['K'], 'phi_ratio_1_0': kt[1.]['phi']/kt[0.]['phi'],
                    'theory_best_fine': max(FINE, key=lambda nu: kt[nu]['psi'])}
    (RESULTS/'descriptive.json').write_text(json.dumps({'cases': {k: {**v, **{f: {str(n): x for n, x in v[f].items()}
                                                                             for f in ['K', 'N', 'evaluation', 'validation',
                                                                                       'eval_ratio_to_0', 'psi_ratio_to_0',
                                                                                       'multiplier']}}
                                                                  for k, v in rows.items()},
                                                        'kinds': kinds}, indent=1)+'\n')
    lines = ['# noise_scale_20261021 descriptive tables (generated by scripts/describe.py)', '',
             'Ranges are across seeds 1–3. Ratios to ν = 0 are evaluation-batch decreases.', '']
    for a in ARMS:
        lines += [f'## {a}', '', '| step | K_0 | K_½ | K_1 | N_1(2048) | Φ_1/Φ_0 | B_required | pair at max | '
                  'theory ν* (fine) | best ν eval | best ν validation | ratio ν=½ | ratio ν=1 |',
                  '| ---: | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |']
        for t in STATES:
            r = [rows[f'{a}_s{s}_t{t}'] for s in SEEDS]
            lines.append(f"| {t} | {span([x['K'][0.] for x in r])} | {span([x['K'][.5] for x in r])} | "
                         f"{span([x['K'][1.] for x in r])} | {span([x['N'][1.] for x in r])} | "
                         f"{span([x['phi_ratio_1_0'] for x in r])} | {span([x['B_required'] for x in r])} | "
                         f"{', '.join(x['argmax_pair'] for x in r)} | {', '.join(str(x['theory_best_fine']) for x in r)} | "
                         f"{', '.join(str(x['best']) for x in r)} | {', '.join(str(x['validation_best']) for x in r)} | "
                         f"{span([x['eval_ratio_to_0'][.5] for x in r], 2)} | {span([x['eval_ratio_to_0'][1.] for x in r], 2)} |")
        lines.append('')
    lines += ['## B_crit per pair (median over seeds)', '', '| arm | step | 0→¼ | ¼→½ | ½→¾ | ¾→1 |',
              '| --- | ---: | --- | --- | --- | --- |']
    for a in ARMS:
        for t in STATES:
            r = [rows[f'{a}_s{s}_t{t}'] for s in SEEDS]
            cells = [f"{statistics.median(x['pairs'][p]['B_crit'] for x in r):.3g}" for p in r[0]['pairs']]
            lines.append(f"| {a} | {t} | {' | '.join(cells)} |")
    lines += ['', '## Per-kind breakdown (median over seeds and the two optimizers)', '',
              '| kind | K_1 step 10 | K_1 step 400 | Φ_1/Φ_0 step 10 | Φ_1/Φ_0 step 400 | theory ν* step 10 | theory ν* step 400 |',
              '| --- | --- | --- | --- | --- | --- | --- |']
    for name, cases in kinds.items():
        at = lambda t, f: statistics.median(cases[f'{a}_s{s}_t{t}'][f] for a in ARMS for s in SEEDS)
        lines.append(f"| {name} | {at(10, 'K1'):.3g} | {at(400, 'K1'):.3g} | {at(10, 'phi_ratio_1_0'):.3g} | "
                     f"{at(400, 'phi_ratio_1_0'):.3g} | {at(10, 'theory_best_fine'):.3g} | {at(400, 'theory_best_fine'):.3g} |")
    lines += ['', '## Theory against measurement by phase (early: steps 10–50; late: steps 100–400)', '',
              '| arm | phase | mean theory ν* (fine) | mean best ν (eval) | median Ψ_½/Ψ_0 | median eval ½/0 | '
              'median Ψ_1/Ψ_0 | median eval 1/0 | median eval decrease ν = 0 / ¼ / ½ / ¾ / 1 |',
              '| --- | --- | --- | --- | --- | --- | --- | --- | --- |']
    for a in ARMS:
        for phase, ts in [('early', summarize.EARLY), ('late', summarize.LATE)]:
            r = [rows[f'{a}_s{s}_t{t}'] for s in SEEDS for t in ts]
            med = lambda f, nu: statistics.median(x[f][nu] for x in r)
            decreases = ' / '.join(f'{med("evaluation", nu):.3g}' for nu in GRID)
            lines.append(f"| {a} | {phase} | {statistics.mean(x['theory_best_fine'] for x in r):.3g} | "
                         f"{statistics.mean(x['best'] for x in r):.3g} | {med('psi_ratio_to_0', .5):.3g} | "
                         f"{med('eval_ratio_to_0', .5):.3g} | {med('psi_ratio_to_0', 1.):.3g} | "
                         f"{med('eval_ratio_to_0', 1.):.3g} | {decreases} |")
    wins = lambda hi, lo: sum(x['evaluation'][hi] > x['evaluation'][lo] for x in rows.values())
    lines += ['', f'- Evaluation decrease of ν = ½ above ν = 0 in {wins(.5, 0.)} of {len(rows)} states; ν = 1 above ν = 0 in '
              f'{wins(1., 0.)}; ν = ¾ above ν = 1 in {wins(.75, 1.)}; ν = ½ above ν = ¾ in {wins(.5, .75)}.',
              f"- Theory ν* (fine) minus best ν (eval), mean over all states: "
              f"{statistics.mean(x['theory_best_fine']-x['best'] for x in rows.values()):.3g}; "
              f"positive in {sum(x['theory_best_fine'] > x['best'] for x in rows.values())} of {len(rows)}."]
    for phase, ts in [('early', summarize.EARLY), ('late', summarize.LATE)]:
        r = [x for x in rows.values() if x['step'] in ts]
        lines.append(f"- {phase}: ν = ½ above ν = ¾ in {sum(x['evaluation'][.5] > x['evaluation'][.75] for x in r)} of "
                     f"{len(r)}; ν = ¾ above ν = 1 in {sum(x['evaluation'][.75] > x['evaluation'][1.] for x in r)} of {len(r)}.")
    cases = summary['cases']
    n1_miss = [k for k, c in cases.items() if not c['theory']['1.0']['K'] > c['theory']['0.5']['K'] > c['theory']['0.0']['K']]
    p1_miss = [f"{k} (theory {c['theory_best_grid']}, best {c['best']})" for k, c in cases.items()
               if abs(GRID.index(c['theory_best_grid'])-GRID.index(c['best'])) > 1]
    f1_miss = [f"{k} (best {c['best']})" for k, c in cases.items() if c['best'] not in (.25, .5, .75)]
    lines += [f"- N1 exceptions: {', '.join(n1_miss) or 'none'}; K_1 > K_½ in "
              f"{sum(c['theory']['1.0']['K'] > c['theory']['0.5']['K'] for c in cases.values())} of {len(cases)}.",
              f"- F1 exceptions: {', '.join(f1_miss) or 'none'}.", f"- P1 exceptions: {', '.join(p1_miss) or 'none'}."]
    agree = sum(x['best'] == x['validation_best'] for x in rows.values())
    edges = sum(len(x['edge']) for x in rows.values())
    lines += ['', f'- Evaluation-best ν equals validation-best ν in {agree} of {len(rows)} states.',
              f'- Selected multipliers at a grid edge: {edges} of {len(rows)*len(GRID)} (state, ν) pairs.',
              f"- Smallest Ritz value over δ: {min(x['min_ritz_over_delta'] for x in rows.values()):.6g}."]
    (RESULTS/'descriptive.md').write_text('\n'.join(lines)+'\n')
    print('\n'.join(lines))


if __name__ == '__main__':
    sys.exit(main())
